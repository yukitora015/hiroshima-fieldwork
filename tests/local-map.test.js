const fs=require('node:fs'), vm=require('node:vm'), assert=require('node:assert/strict');
const ctx={window:{addEventListener(){}},Math,Number,Array,document:{},fetch(){throw Error('unexpected')}};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync('site/js/local-map.js','utf8'),ctx);
ctx.FieldworkLocalMap=ctx.window.FieldworkLocalMap;
vm.runInContext(fs.readFileSync('site/js/nav-guide.js','utf8'),ctx);
const m=ctx.FieldworkLocalMap;
assert.ok(Math.abs(m.bearing([0,0],[1,0]))<0.01);
assert.ok(Math.abs(m.bearing([0,0],[0,1])-90)<0.01);
assert.ok(Math.abs(m.bearing([0,0],[-1,0])-180)<0.01);
assert.equal(m.heading({point:[0,0],future:[[0,0],[0,0.001]],past:[[0,-0.001],[0,0]]}),90);
assert.equal(m.heading({point:[0,0],future:[[0,0]],past:[[0,-0.001],[0,0]]}),90);
const path=[[34.39,132.45],[34.39,132.46]];
const turns=[{type:'depart',location:path[0]},{type:'arrive',location:path[1]}];
const list=ctx.window.FieldworkNavigator.addStraightPoints(path,turns);
assert.ok(list.some(x=>x.modifier==='straight'));
assert.ok(list.every(x=>Math.abs(x.location[0]-34.39)<1e-8));
assert.equal(list[0].type,'depart'); assert.equal(list.at(-1).type,'arrive');
console.log('PASS: cardinal bearings, arrival direction, and on-route straight points');
